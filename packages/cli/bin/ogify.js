#!/usr/bin/env node
import { readFile } from "node:fs/promises";

const [command, ...args] = process.argv.slice(2);
const apiKey = process.env.OGIFY_API_KEY;
const base = (process.env.OGIFY_API_URL || "https://api.ogify.online").replace(/\/$/, "");
if (!apiKey) fail("Set OGIFY_API_KEY before using the CLI.");

const flag = (name, fallback) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
};

let endpoint;
let payload;
if (command === "screenshot") {
  const url = args[0]; if (!url) fail("Usage: ogify screenshot <url> [--format png|jpeg|webp] [--full-page true]");
  endpoint = "/v1/render/url";
  payload = { url, format: flag("format", "png"), full_page: flag("full-page", "false") === "true" };
} else if (command === "social") {
  const url = args[0]; if (!url) fail("Usage: ogify social <url> [--title text]");
  endpoint = "/v1/render/social";
  payload = { url, title: flag("title") };
} else if (command === "template") {
  endpoint = "/v1/render/template";
  payload = { template: flag("template", "blog"), title: flag("title", "Generated by Ogify"), author: flag("author") };
} else if (command === "html") {
  const file = args[0]; if (!file) fail("Usage: ogify html <file.html> [--format png|jpeg|webp]");
  endpoint = "/v1/render/html";
  payload = { html: await readFile(file, "utf8"), format: flag("format", "png") };
} else if (command === "pdf") {
  const url = args[0]; if (!url) fail("Usage: ogify pdf <url> [--format A4|Letter|Legal|A3]");
  endpoint = "/v1/render/pdf";
  payload = { url, format: flag("format", "A4"), landscape: flag("landscape", "false") === "true" };
} else if (command === "metadata") {
  const url = args[0]; if (!url) fail("Usage: ogify metadata <url>");
  endpoint = "/v1/extract/metadata";
  payload = { url };
} else if (command === "content") {
  const url = args[0]; if (!url) fail("Usage: ogify content <url> [--selector main] [--links true]");
  endpoint = "/v1/extract/content";
  payload = { url, selector: flag("selector"), include_links: flag("links", "false") === "true" };
} else if (command === "usage") {
  const res = await fetch(`${base}/v1/me/usage`, { headers: { "x-api-key": apiKey } });
  console.log(JSON.stringify(await res.json(), null, 2)); process.exit(res.ok ? 0 : 1);
} else {
  fail("Commands: screenshot, social, template, html, pdf, metadata, content, usage");
}

const response = await fetch(`${base}${endpoint}`, {
  method: "POST",
  headers: { "Content-Type": "application/json", "x-api-key": apiKey },
  body: JSON.stringify(payload),
});
const data = await response.json();
console.log(JSON.stringify(data, null, 2));
process.exit(response.ok ? 0 : 1);

function fail(message) { console.error(message); process.exit(1); }
