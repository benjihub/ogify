"use client";

import { useState } from "react";
import { cn } from "@/lib/utils";
import { getApiBaseUrl } from "@/lib/api-base";

const API_BASE = getApiBaseUrl();
type Mode = "template" | "screenshot" | "social" | "html" | "pdf" | "metadata" | "content";

export function RenderStudio() {
  const [mode, setMode] = useState<Mode>("template");
  const [apiKey, setApiKey] = useState("");
  const [title, setTitle] = useState("Launch day: generated by Ogify");
  const [url, setUrl] = useState("https://ogify.online");
  const [template, setTemplate] = useState("blog");
  const [html, setHtml] = useState('<main style="display:grid;place-items:center;width:100vw;height:100vh;background:#111827;color:white;font-family:Arial"><h1>Hello from Ogify</h1></main>');
  const [resultUrl, setResultUrl] = useState<string | null>(null);
  const [imageError, setImageError] = useState("");
  const [jsonResult, setJsonResult] = useState<string>("");
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);

  async function render() {
    setBusy(true);
    setError("");
    setResultUrl(null);
    setImageError("");
    setJsonResult("");
    try {
      if (!apiKey.trim()) throw new Error("Paste an API key for this browser session. The dashboard does not persist it.");
      const config = requestForMode(mode, { title, url, template, html });
      const response = await fetch(`${API_BASE}${config.endpoint}`, {
        method: "POST",
        headers: { "Content-Type": "application/json", "x-api-key": apiKey.trim() },
        body: JSON.stringify(config.payload),
      });
      const data = await response.json() as { url?: string; image_url?: string; error?: string; request_id?: string; metadata?: unknown };
      if (!response.ok) throw new Error(`${data.error || `Request failed (${response.status})`}${data.request_id ? ` · request ${data.request_id}` : ""}`);
      const publicUrl = data.url || data.image_url || null;
      if (mode !== "pdf" && ["template", "screenshot", "social", "html"].includes(mode) && !publicUrl) {
        throw new Error("Render succeeded but the API did not return an image URL.");
      }
      if (publicUrl && mode !== "pdf") setResultUrl(resolveApiUrl(publicUrl));
      setJsonResult(JSON.stringify(data, null, 2));
    } catch (err) {
      setError(err instanceof Error ? err.message : "Request failed.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <section id="render-studio" className="rounded-2xl border border-line-dim bg-ink-soft/80 p-4 shadow-sm sm:p-6">
      <div className="mb-1 text-base font-semibold tracking-tight text-paper">Developer render studio</div>
      <p className="mb-5 text-sm leading-6 text-muted">Test the same production endpoints your application will call. Your API key stays in this browser session.</p>

      <div className="mb-5 flex flex-wrap gap-1.5 rounded-xl border border-line-dim bg-ink p-1.5">
        {(["template", "screenshot", "social", "html", "pdf", "metadata", "content"] as Mode[]).map((item) => (
          <button type="button" key={item} aria-pressed={mode === item} onClick={() => setMode(item)} className={cn("rounded-lg border border-transparent px-3 py-2 text-xs font-semibold capitalize transition", mode === item ? "border-cinnabar/30 bg-cinnabar text-white shadow-sm" : "text-muted hover:bg-ink-soft hover:text-paper")}>
            {item}
          </button>
        ))}
      </div>

      <div className="grid gap-6 lg:grid-cols-[0.85fr_1.15fr]">
        <div className="space-y-4">
          <Field label="API key"><input type="password" value={apiKey} onChange={(e) => setApiKey(e.target.value)} placeholder="ogfy_live_…" autoComplete="off" className={inputClass} /></Field>

          {mode === "template" && <Field label="Template"><select value={template} onChange={(e) => setTemplate(e.target.value)} className={inputClass}><option value="blog">Blog</option><option value="product">Product</option><option value="saas">SaaS</option></select></Field>}
          {(mode === "template" || mode === "social") && <Field label="Title override"><input value={title} onChange={(e) => setTitle(e.target.value)} className={inputClass} /></Field>}
          {(mode === "screenshot" || mode === "social" || mode === "pdf" || mode === "metadata" || mode === "content") && <Field label="Public URL"><input value={url} onChange={(e) => setUrl(e.target.value)} className={inputClass} /></Field>}
          {mode === "html" && <Field label="HTML"><textarea value={html} onChange={(e) => setHtml(e.target.value)} rows={9} className={`${inputClass} resize-y`} /></Field>}

          <button type="button" onClick={render} disabled={busy} className="inline-flex min-h-11 w-full items-center justify-center rounded-xl bg-cinnabar px-4 py-3 text-sm font-semibold text-white shadow-sm transition hover:bg-cinnabar-dark disabled:cursor-not-allowed disabled:opacity-50">
            {busy ? "Working…" : mode === "pdf" ? "Generate PDF" : mode === "metadata" || mode === "content" ? "Extract" : "Render"}
          </button>
          {error && <p role="alert" className="rounded-xl border border-cinnabar/25 bg-cinnabar/10 p-3 text-sm leading-5 text-cinnabar">{error}</p>}
          <p className="text-xs leading-5 text-muted">For production, call Ogify only from your server or trusted build environment. Never ship a secret API key to client JavaScript.</p>
        </div>

        <div className="space-y-3">
          <div className="aspect-[1200/630] overflow-hidden rounded-2xl border border-line-dim bg-ink shadow-inner">
            {resultUrl ? /* eslint-disable-next-line @next/next/no-img-element */ <img src={resultUrl} alt="Ogify render result" onLoad={() => setImageError("")} onError={() => setImageError("The API returned an image URL, but the browser could not load it.")} className="h-full w-full object-contain" /> : <div className="grid h-full place-items-center px-8 text-center text-sm leading-6 text-muted">Image output appears here. PDF requests return a hosted URL in the response below.</div>}
          </div>
          {imageError && <p role="alert" className="rounded-xl border border-cinnabar/25 bg-cinnabar/10 p-3 text-sm leading-5 text-cinnabar">{imageError}</p>}
          {jsonResult && <pre className="code-card max-h-64 overflow-auto text-[11px]">{jsonResult}</pre>}
        </div>
      </div>
    </section>
  );
}

function resolveApiUrl(value: string): string {
  try {
    return new URL(value, `${API_BASE}/`).toString();
  } catch {
    return value;
  }
}

function requestForMode(mode: Mode, values: { title: string; url: string; template: string; html: string }) {
  switch (mode) {
    case "template": return { endpoint: "/v1/render/template", payload: { template: values.template, title: values.title, author: "Ogify Render Studio", tag: "Preview" } };
    case "screenshot": return { endpoint: "/v1/render/url", payload: { url: values.url, viewport_width: 1200, viewport_height: 630, delay: 500, format: "png" } };
    case "social": return { endpoint: "/v1/render/social", payload: { url: values.url, title: values.title || undefined, width: 1200, height: 630 } };
    case "html": return { endpoint: "/v1/render/html", payload: { html: values.html, width: 1200, height: 630, format: "png" } };
    case "pdf": return { endpoint: "/v1/render/pdf", payload: { url: values.url, format: "A4", print_background: true } };
    case "metadata": return { endpoint: "/v1/extract/metadata", payload: { url: values.url } };
    case "content": return { endpoint: "/v1/extract/content", payload: { url: values.url, selector: "main", include_links: true } };
  }
}

function Field({ label, children }: { label: string; children: React.ReactNode }) {
  return <label className="block text-xs font-semibold text-fg"><span className="mb-1.5 block">{label}</span>{children}</label>;
}

const inputClass = "w-full rounded-xl border border-line-dim bg-ink px-3.5 py-3 text-sm text-fg placeholder:text-muted focus:border-cinnabar focus:outline-none focus:ring-4 focus:ring-cinnabar/10";
