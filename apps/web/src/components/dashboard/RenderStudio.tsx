"use client";

import { useEffect, useRef, useState } from "react";
import { cn } from "@/lib/utils";

const API_BASE = process.env.NEXT_PUBLIC_API_URL || "https://api.ogify.online";
type Mode = "template" | "url" | "composite";

export function RenderStudio() {
  const [mode, setMode] = useState<Mode>("template");
  const [apiKey, setApiKey] = useState("");
  const [title, setTitle] = useState("Launch day: generated by Ogify");
  const [url, setUrl] = useState("https://ogify.online");
  const [template, setTemplate] = useState("blog");
  const [resultUrl, setResultUrl] = useState<string | null>(null);
  const [publicUrl, setPublicUrl] = useState<string | null>(null);
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);
  const objectUrl = useRef<string | null>(null);

  useEffect(() => () => { if (objectUrl.current) URL.revokeObjectURL(objectUrl.current); }, []);

  async function render() {
    setBusy(true); setError(""); setPublicUrl(null);
    try {
      if (!apiKey.trim()) throw new Error("Paste an API key for this browser session. It is never stored by Ogify's web app.");
      const endpoint = mode === "template" ? "/v1/render/template" : mode === "url" ? "/v1/render/url" : "/v1/render/composite";
      const payload = mode === "template"
        ? { template, title, author: "Ogify Render Studio", tag: "Preview" }
        : mode === "url"
          ? { url, viewport_width: 1200, viewport_height: 630, delay: 500 }
          : { url, title, author: "Captured with Ogify", tag: "Website preview", width: 1200, height: 630, viewport_width: 1280, viewport_height: 800, delay: 500 };
      const response = await fetch(`${API_BASE}${endpoint}`, { method: "POST", headers: { "Content-Type": "application/json", "x-api-key": apiKey.trim() }, body: JSON.stringify(payload) });
      const data = await response.json() as { image_url?: string; error?: string; request_id?: string };
      if (!response.ok || !data.image_url) throw new Error(`${data.error || `Render failed (${response.status})`}${data.request_id ? ` · request ${data.request_id}` : ""}`);
      setPublicUrl(data.image_url);
      setResultUrl(data.image_url);
    } catch (err) { setError(err instanceof Error ? err.message : "Render failed."); }
    finally { setBusy(false); }
  }

  return (
    <section className="rounded border border-line-dim bg-ink-soft p-6">
      <div className="mb-1 font-mono text-[10.5px] uppercase tracking-wider text-gold">Render studio</div>
      <p className="mb-5 font-mono text-[11px] text-muted">Test template, screenshot and composite rendering without leaving your dashboard.</p>
      <div className="mb-5 flex flex-wrap gap-2">
        {(["template","url","composite"] as Mode[]).map((item) => <button key={item} onClick={() => setMode(item)} className={cn("rounded border px-3 py-2 font-mono text-[11px] uppercase", mode === item ? "border-cinnabar bg-cinnabar/10 text-paper" : "border-line-dim text-muted")}>{item === "url" ? "Screenshot" : item}</button>)}
      </div>
      <div className="grid gap-6 lg:grid-cols-[0.8fr_1.2fr]">
        <div className="space-y-4">
          <div><label className="mb-1.5 block font-mono text-[10px] uppercase tracking-wider text-muted">API key</label><input type="password" value={apiKey} onChange={(e)=>setApiKey(e.target.value)} placeholder="ogfy_live_…" autoComplete="off" className="w-full rounded border border-line-dim bg-ink px-3 py-2.5 font-mono text-xs text-fg focus:border-cinnabar focus:outline-none" /></div>
          {mode === "template" && <div><label className="mb-1.5 block font-mono text-[10px] uppercase tracking-wider text-muted">Template</label><select value={template} onChange={(e)=>setTemplate(e.target.value)} className="w-full rounded border border-line-dim bg-ink px-3 py-2.5 text-sm text-fg"><option value="blog">Blog</option><option value="product">Product</option><option value="saas">SaaS</option></select></div>}
          {mode !== "url" && <div><label className="mb-1.5 block font-mono text-[10px] uppercase tracking-wider text-muted">Title</label><input value={title} onChange={(e)=>setTitle(e.target.value)} className="w-full rounded border border-line-dim bg-ink px-3 py-2.5 text-sm text-fg focus:border-cinnabar focus:outline-none" /></div>}
          {mode !== "template" && <div><label className="mb-1.5 block font-mono text-[10px] uppercase tracking-wider text-muted">Public URL</label><input value={url} onChange={(e)=>setUrl(e.target.value)} className="w-full rounded border border-line-dim bg-ink px-3 py-2.5 text-sm text-fg focus:border-cinnabar focus:outline-none" /></div>}
          <button onClick={render} disabled={busy} className="w-full rounded bg-cinnabar px-4 py-3 font-mono text-xs uppercase tracking-wide text-paper disabled:opacity-50">{busy ? "Rendering…" : "Render & create public URL"}</button>
          {error && <p className="font-mono text-[11px] leading-relaxed text-cinnabar">{error}</p>}
          <p className="font-mono text-[10px] leading-relaxed text-line">For safety, this tool does not save your raw API key. Production applications should keep keys on the server.</p>
        </div>
        <div>
          <div className="aspect-[1200/630] overflow-hidden rounded border border-line-dim bg-ink">{resultUrl ? /* eslint-disable-next-line @next/next/no-img-element */ <img src={resultUrl} alt="Ogify render result" className="h-full w-full object-cover" /> : <div className="grid h-full place-items-center px-8 text-center font-mono text-xs text-line">Your rendered image will appear here.</div>}</div>
          {publicUrl && <div className="mt-3 rounded border border-line-dim bg-ink p-3"><div className="mb-1 font-mono text-[9px] uppercase tracking-wider text-gold">Public OG image URL</div><div className="break-all font-mono text-[11px] text-fg">{publicUrl}</div><button onClick={() => navigator.clipboard.writeText(publicUrl)} className="mt-2 font-mono text-[10px] text-cinnabar hover:underline">Copy URL</button></div>}
        </div>
      </div>
    </section>
  );
}
